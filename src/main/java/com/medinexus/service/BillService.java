package com.medinexus.service;

import com.medinexus.model.Bill;
import com.medinexus.repository.BillJdbcRepository;

import java.time.LocalDateTime;
import java.util.List;

public class BillService {

    private final BillJdbcRepository repository =
            new BillJdbcRepository();

    // ---------------------------------------------------------
    // GET ALL BILLS
    // ---------------------------------------------------------

    public List<Bill> getAllBills() {
        return repository.findAll();
    }

    // ---------------------------------------------------------
    // GET BILL BY ID
    // ---------------------------------------------------------

    public Bill getBillById(int billId) {
        return repository.findById(billId);
    }

    // ---------------------------------------------------------
    // GET BILLS FOR A PATIENT
    // ---------------------------------------------------------

    public List<Bill> getPatientBills(int patientId) {
        return repository.findByPatientId(patientId);
    }

    // ---------------------------------------------------------
    // GET BILL BY APPOINTMENT
    // ---------------------------------------------------------

    public Bill getBillByAppointment(int appointmentId) {
        return repository.findByAppointmentId(appointmentId);
    }

    // ---------------------------------------------------------
    // CREATE BILL
    // ---------------------------------------------------------

    public Bill createBill(Bill bill) {

        if (bill == null) {
            throw new IllegalArgumentException(
                    "Bill cannot be null."
            );
        }

        validateCharges(bill);

        // Calculate total automatically
        double total =
                bill.getConsultationCharge()
                        + bill.getMedicineCharge()
                        + bill.getOtherCharges();

        bill.setTotalAmount(total);

        // Default payment status
        if (bill.getPaymentStatus() == null
                || bill.getPaymentStatus().isBlank()) {

            bill.setPaymentStatus("PENDING");
        }

        // Set creation time automatically
        if (bill.getCreatedAt() == null) {

            bill.setCreatedAt(
                    LocalDateTime.now()
            );
        }

        /*
         * Bill ID is generated by MySQL AUTO_INCREMENT.
         * The repository inserts the bill without bill_id
         * and retrieves the generated ID.
         */
        return repository.add(bill);
    }

    // ---------------------------------------------------------
    // UPDATE BILL
    // ---------------------------------------------------------

    public void updateBill(Bill bill) {

        if (bill == null) {
            throw new IllegalArgumentException(
                    "Bill cannot be null."
            );
        }

        validateCharges(bill);

        // Recalculate total whenever bill is updated
        double total =
                bill.getConsultationCharge()
                        + bill.getMedicineCharge()
                        + bill.getOtherCharges();

        bill.setTotalAmount(total);

        repository.update(bill);
    }

    // ---------------------------------------------------------
    // MARK BILL AS PAID
    // ---------------------------------------------------------

    public void markAsPaid(int billId) {

        Bill bill =
                repository.findById(billId);

        if (bill == null) {
            throw new IllegalArgumentException(
                    "Bill not found."
            );
        }

        bill.setPaymentStatus("PAID");

        repository.update(bill);
    }

    // ---------------------------------------------------------
    // VALIDATE BILL CHARGES
    // ---------------------------------------------------------

    private void validateCharges(Bill bill) {

        if (bill.getConsultationCharge() < 0
                || bill.getMedicineCharge() < 0
                || bill.getOtherCharges() < 0) {

            throw new IllegalArgumentException(
                    "Charges cannot be negative."
            );
        }
    }
}